    public void guardarCargos(String id) {
        String[] emp = xmls.leerXml();
        String fpago=" ";
        if(efectivo.isSelected())
            fpago="efectivo";
        else if(debito.isSelected())
            fpago="debito";
        else if(credito.isSelected())
            fpago="credito";
        else if(cheques.isSelected())
            fpago="cheques";
        else if(otros.isSelected())
            fpago="otros";
        
        int sc = sql.SelectCount("cargoshab", "huesped='"+id+"'");
        if(sc>0)
        {
            sql.Delete("cargoshab", "huesped='"+id+"'");
        }
        int w=tablapagos.getRowCount();
        for(int i=0;i<w;i++){
            String consu="0",pago="0";
            if(tablapagos.getValueAt(i, 6)!=null)
                consu=tablapagos.getValueAt(i, 6).toString();
            if(tablapagos.getValueAt(i, 7)!=null)
                pago=tablapagos.getValueAt(i, 7).toString();
            sql.Insert("cargoshab", "fecha, "
                + "serv, "
                + "dep, "
                + "cantidad, "
                + "puni, "
                + "consumo, "
                + "pago, "
                + "huesped, "
                + "empleado, "
                + "formapago, "
                + "tarjeta, "
                + "numero", 
                      "'"+tablapagos.getValueAt(i, 0)+"', "
                    + "'"+tablapagos.getValueAt(i, 1)+"', "
                    + "(select id from departamento where nombre='"+emp[5]+"'), "
                    + "'"+tablapagos.getValueAt(i, 3)+"', "
                    + "'"+tablapagos.getValueAt(i, 4)+"', "
                    + "'"+consu+"', "
                    + "'"+pago+"', "
                    + "'"+id+"', "
                    + "(select id from empleado where persona='"+emp[7]+"'), "
                    + "'"+fpago+"', "
                    + "(select id from tarjetas where nombre='"+tipoTarjeta.getSelectedItem()+"'), "
                    + "'"+num1.getText()+num2.getText()+num3.getText()+num4.getText()+"'");
        }
    }
    
    public void cargos(Object[] data) {
        tables.delrow(tablapagos);
        if(data!=null)
        {
            String[] leer = xmls.leerXml();
            String ap = leer[9].substring(0, 1).toUpperCase();
            String nom1 = leer[8].substring(0, 1).toUpperCase();
            int l = leer[8].length();
            String nom2 = leer[8].substring(1, l).toLowerCase();
            String dep=(ap+" "+nom1+nom2);
            if(dep.length()>15)
                dep=dep.substring(0, 15);
            tables.addrow(tablapagos);
            tablapagos.setValueAt(data[1], 0, 0);
            tablapagos.setValueAt(data[0], 0, 1);
            tablapagos.setValueAt(dep, 0, 2);
            tablapagos.setValueAt(1, 0, 3);
            tablapagos.setValueAt(String.format("%.2f", data[3]), 0, 4);
            tablapagos.setValueAt(String.format("%.2f", data[3]), 0, 5);
            tablapagos.setValueAt(String.format("%.2f", data[3]), 0, 6);
            totalPago.setText(String.format("%.2f", data[3]));
            int dias=Integer.parseInt(data[2].toString());
            for(int i=1;i<dias;i++){
                tables.addrow(tablapagos);
                tablapagos.setValueAt(codex.sumarFechasDias((Date) data[1], i), i, 0);
                tablapagos.setValueAt(data[0], i, 1);
                tablapagos.setValueAt(dep, i, 2);
                tablapagos.setValueAt(1, i, 3);
                tablapagos.setValueAt(String.format("%.2f", data[3]), i, 4);
                tablapagos.setValueAt(String.format("%.2f", data[3]), i, 5);
                float last = val.stringtofloat(totalPago.getText());
                float news = val.stringtofloat(tablapagos.getValueAt(i, 5).toString());
                tablapagos.setValueAt(String.format("%.2f", last+news), i, 6);
                totalPago.setText(String.format("%.2f", last+news));
            }
        }
    }
    
