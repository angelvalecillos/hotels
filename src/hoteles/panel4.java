    private void haberDeber(String huesped) {
    int x = tablapagos.getRowCount();
    String hab = "";
    
    List<Map<String, Object>> resultados = sql.SqlQuery("SELECT habitacion.numero FROM public.habitacion, public.huesped WHERE huesped.hab = habitacion.id AND idguest ='" + huesped + "'");
    if (!resultados.isEmpty()) {
        hab = resultados.get(0).get("numero").toString().trim();
    }
    
    if (x > 0) {
        String sertab = tablapagos.getValueAt(0, 1).toString().trim();
        if (sertab.equals(hab)) {
            // CORREGIDO: Manejo seguro de conversión
            String puniStr = tablapagos.getValueAt(0, 4) != null ? tablapagos.getValueAt(0, 4).toString() : "0";
            float puni = val.stringtofloat(puniStr);
            
            String cantStr = tablapagos.getValueAt(0, 3) != null ? tablapagos.getValueAt(0, 3).toString() : "0";
            int cant = Integer.parseInt(cantStr);
            
            float tot = puni * cant;
            tablapagos.setValueAt(String.format("%.2f", tot), 0, 5);
            tablapagos.setValueAt(String.format("%.2f", tot), 0, 6);
            totalPago.setText(String.format("%.2f", tot));
            tablapagos.setValueAt("", 0, 7);
        }
        
        // ... resto del código con conversiones seguras similares
    }
}
    
    private void addpago() {
        if (servicio.getText().length()>2&&servtotal.getText().length()>0)
        {
            String[] leer = xmls.leerXml();
            String ap = leer[9].substring(0, 1).toUpperCase();
            String nom1 = leer[8].substring(0, 1).toUpperCase();
            int l = leer[8].length();
            String nom2 = leer[8].substring(1, l).toLowerCase();
            String dep=(ap+" "+nom1+nom2);
            if(dep.length()>15)
                dep=dep.substring(0, 15);
            tables.addrow(tablapagos);
            int x = tablapagos.getRowCount()-1;
            java.util.Date date = new java.util.Date();
            java.sql.Date date1=new java.sql.Date(date.getYear(), date.getMonth(), date.getDate());
            tablapagos.setValueAt(date1, x, 0);
            tablapagos.setValueAt(servicio.getText().trim(), x, 1);
            tablapagos.setValueAt(dep, x, 2);
            tablapagos.setValueAt(1, x, 3);
            float s = val.stringtofloat(servtotal.getText());
            tablapagos.setValueAt(String.format("%.2f", s), x, 4);
            tablapagos.setValueAt(String.format("%.2f", s), x, 5);
            String dato = totalPago.getText();
            float w = val.stringtofloat(dato);
            tablapagos.setValueAt(String.format("%.2f", w-s), x, 7);
            totalPago.setText(String.format("%.2f", w-s));
        }
    }
    
