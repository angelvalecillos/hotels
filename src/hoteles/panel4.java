    private void selectpago(int tipo) {
        boolean efe = false,deb = false,cre = false,che = false,otr = false;
        switch (tipo) {
            case 1:
                efe=true;
                break;
            case 2:
                deb=true;
                break;
            case 3:
                cre=true;
                break;
            case 4:
                che=true;
                break;
            case 5:
                otr=true;
                break;
            default:
                break;
        }
        efectivo.setSelected(efe);
        debito.setSelected(deb);
        credito.setSelected(cre);
        cheques.setSelected(che);
        otros.setSelected(otr);
    }

