    public String[] guardardespues() {
    String paisNombre = pais1.getSelectedItem().toString();
    String vehiculoText = vehiculo.getText();
    String observacionText = opsnuevo.getText();
    
    String paisId = "";
    
    try {
        List<Map<String, Object>> rows = sql.SqlQuery(
            "SELECT id FROM pais WHERE nombre ILIKE  '%" + paisNombre.trim() + "%'");
        
        if (!rows.isEmpty()) {
            Object idObj = rows.get(0).get("id");
            if (idObj != null) {
                paisId = idObj.toString().trim();
            }
        }
    } catch (Exception ex) {
        Logger.getLogger(IngresoHuesped.class.getName()).log(Level.SEVERE, null, ex);
        // En caso de error, dejamos paisId vacío
    }
    
    String[] send = {paisId, vehiculoText.trim(), observacionText.trim()};
    return send;
}
    
    
    private boolean guardartelefono(String id){
        boolean test=false;
        String tel = telefono.getText();
        int l = tel.length();
        if(l>5){
            if(tel.contains(",")){
                l=tel.split(",").length;
                String[] split = tel.split(",");
                for(int i=0;i<l;i++){
                    test=savephone(id, split[i]);
                }
            }
            else
                test=this.savephone(id, tel);
        }
        else if(l==0)
            test = sql.Delete("per_tel", "persona='"+id+"'");
        
        return test;
    }
    
    private boolean  savephone(String id, String phone){

        boolean test=false;
        int SelectCount = sql.SelectCount("per_tel","persona='"+id+"'");
        if(SelectCount==1)
        {
            test = sql.Update("per_tel", "telefono='"+phone.trim()+"'", "persona='"+id.trim()+"'");
        }
        else if(SelectCount==0)
        {
            test=sql.Insert("per_tel", "persona ,telefono","'"+id.trim()+"','"+phone.trim()+"'");
        }
        return test;
    }
    
