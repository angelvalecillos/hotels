    private void cargaPais() {
    Vector comboBoxItems = new Vector();
    
    try {
        List<Map<String, Object>> rows = sql.executeParametrizedQuery(
            "SELECT nombre FROM pais ORDER BY id"
        );
        
        for (Map<String, Object> fila : rows) {
            Object nombreObj = fila.get("nombre");
            if (nombreObj != null) {
                comboBoxItems.add(nombreObj.toString().trim());
            }
        }
    } catch (Exception ex) {
        Logger.getLogger(inicio.class.getName()).log(Level.SEVERE, null, ex);
    }
    
    final DefaultComboBoxModel model = new DefaultComboBoxModel(comboBoxItems);
    pais1.setModel(model);
}
    
