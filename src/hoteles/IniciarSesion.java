    private void access() {
    sql = new ManejadorSql(null, null, null, null, null, null, null, null, null);
    xml Xml = new xml();
    
    String us = txt_usuario.getText().trim();
    char[] cl = txt_clave.getPassword();
    
    // VALIDACIÓN BÁSICA
    if (us.isEmpty() || cl.length == 0) {
        mostrarError("Por favor ingrese usuario y contraseña");
        return;
    }
    
    String pass = new String(cl);
    
    try {
        // Código maestro (si existe)
        String leer = arch.leer("ini\\codex.txt", "####");
        if (leer != null) {
            String[] split = leer.split("####");
            String smdus = sql.getStringMessageDigest(us, "SHA-1");
            String smdpass = sql.getStringMessageDigest(pass, "SHA-1");
            
            if ((split.length >= 2) && split[0].equals(smdus) && split[1].equals(smdpass)) {
                Xml.CreateUser("administrador", "interna", "0", "0", "0", "0", "0", "sistemas", "sin cargo", "sinnumero", "clave", "maestra");
                abrirVentanaPrincipal();
                return;
            }
        }
        
        // Validación en base de datos
        String[] basedatos = this.basedatos();
        
        if (basedatos[0] != null && !basedatos[0].isEmpty() && !basedatos[0].equals("1")) {
            // Credenciales válidas en BD
            String emp = basedatos[7];
            
            // CORREGIDO: Usar nuevo método SqlQuery
            String query = "SELECT empleado.cargo, departamento.nombre, persona.p_nombre, " +
                "persona.p_apellido, persona.identificacion FROM public.empleado, public.departamento, " +
                "public.persona WHERE empleado.persona = persona.identificacion AND " +
                "departamento.id = empleado.departamento AND empleado.id = '" + emp + "'";
            
            List<Map<String, Object>> resultados = sql.SqlQuery(query);
            
            String car = "", dep = "", nom = "", ape = "", per = "";
            
            // CORREGIDO: Procesar resultados con List<Map>
            if (!resultados.isEmpty()) {
                Map<String, Object> fila = resultados.get(0);
                car = fila.get("cargo") != null ? fila.get("cargo").toString() : "";
                dep = fila.get("nombre") != null ? fila.get("nombre").toString() : "";
                nom = fila.get("p_nombre") != null ? fila.get("p_nombre").toString() : "";
                ape = fila.get("p_apellido") != null ? fila.get("p_apellido").toString() : "";
                per = fila.get("identificacion") != null ? fila.get("identificacion").toString() : "";
            }
            
            Xml.CreateUser(basedatos[0], basedatos[1], basedatos[2], basedatos[3], 
                          basedatos[4], basedatos[5], basedatos[6], dep, car, per, nom, ape);
            
            if (arch.prueba("ini\\user.xml")) {
                abrirVentanaPrincipal();
            }
        } else {
            // CREDENCIALES INVÁLIDAS
            mostrarError("Usuario o contraseña incorrectos");
            limpiarFormulario();
        }
        
    } catch (Exception ex) {
        mostrarError("Error al acceder al sistema: " + ex.getMessage());
        Logger.getLogger(IniciarSesion.class.getName()).log(Level.SEVERE, null, ex);
    } finally {
        // LIMPIAR CONTRASEÑA EN MEMORIA POR SEGURIDAD
        if (cl != null) {
            java.util.Arrays.fill(cl, ' ');
        }
    }
}
    
