    private String[] basedatos() {
    String[] usuario = {"", "", "", "", "", "", "", ""}; 
    
    char[] cl = txt_clave.getPassword();
    if (cl.length == 0) {
        if (cl != null) java.util.Arrays.fill(cl, ' ');
        return usuario; 
    }
    
    try {
        String pass = new String(cl);
        String smdpass = sql.getStringMessageDigest(pass, "SHA-1");
        String user = txt_usuario.getText().trim();
        
        // ✅ CORREGIDO: Usar método seguro parametrizado
        List<Map<String, Object>> resultados = sql.validarUsuarioSeguro(user, smdpass);
        
        if (!resultados.isEmpty()) {
            Map<String, Object> fila = resultados.get(0);
            usuario[0] = getSafeString(fila, "usuario");
            usuario[1] = getSafeString(fila, "clave");
            usuario[2] = getSafeString(fila, "permiso");
            usuario[3] = getSafeString(fila, "clave_ant");
            usuario[4] = getSafeString(fila, "f_u_clave");
            usuario[5] = getSafeString(fila, "pregunta");
            usuario[6] = getSafeString(fila, "respuesta");
            usuario[7] = getSafeString(fila, "empleado");
        }
    } catch (Exception e) {
        Logger.getLogger(IniciarSesion.class.getName()).log(Level.SEVERE, null, e);
    } finally {
        // LIMPIEZA SEGURA
        if (cl != null) java.util.Arrays.fill(cl, ' ');
    }
    
    return usuario;
}

    private String getSafeString(Map<String, Object> map, String key) {
    Object value = map.get(key);
    return value != null ? value.toString().trim() : "";
}

    private void validarCampos(java.awt.event.KeyEvent evt){
        validaciones val = new validaciones();
        txt_mensaje.setText("");
        val.permitir_espacio(evt);
        val.longitud_Field(txt_usuario, 12, evt);
        int length = txt_usuario.getText().length();
        char[] password = txt_clave.getPassword();
        int pass = password.length;
        if(length>5)
            txt_usuario.setForeground(Color.green);        
        else
            txt_usuario.setForeground(Color.red);
        if(pass>5)
            txt_clave.setForeground(Color.green);        
        else
            txt_clave.setForeground(Color.red);
        Color colorg = Color.green;
        Color cusu = txt_usuario.getForeground();
        Color ccod = txt_clave.getForeground();
        if((cusu==colorg)&&(ccod==colorg))
        {
            bntEntrar.setEnabled(true);
            bntEntrar.setBackground(Color.green);
        }
            
        else
        {
            bntEntrar.setEnabled(false);
            bntEntrar.setBackground(Color.gray);
        }
    }
    
    
