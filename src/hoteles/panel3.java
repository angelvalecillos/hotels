    public boolean pax(int ac){
        int v1=Integer.parseInt(adulto.getValue().toString());
        int v2=Integer.parseInt(menor.getValue().toString());
        if(ac == v1+v2){
            adulto.setForeground(Color.red);
            menor.setForeground(Color.red);
        }
        else
        {
            adulto.setForeground(Color.blue);
            menor.setForeground(Color.blue);
        }
        return ac==v1+v2;
    }

    private void calc(){
        if(indate.getDate()!=null&&outdate.getDate()!=null&&intime.getText().length()>3&&outtime.getText().length()>3)
        {
            Date datei = indate.getDate();
            Date dateo = outdate.getDate();
            String timei = intime.getText();
            String timeo = outtime.getText();
            int li=timei.split(":").length;
            int lo=timeo.split(":").length;
            if((datei!=null)||(dateo!=null)||(li>1)||(lo>1))
            {
                int horo=11,hori=1;
                boolean pmi,pmo;
                pmi=timei.endsWith("pm");
                pmo=timeo.endsWith("pm");
                String[] split = timei.split(":");
                timei=split[0];
                split = timeo.split(":");
                timeo=split[0];
                if(!"".equals(timei))
                    hori = Integer.parseInt(timei);
                if(!"".equals(timeo))
                    horo = Integer.parseInt(timeo);
                if(pmi)
                    hori=hori+12;
                if(pmo)
                    horo=horo+12;
                int diasEst = codex.diferenciasDeFechas(datei, dateo);
                if(hori<13){
                    diasEst++;
                    antes=true;
                }
                else
                    antes=false;
                if(horo>11){
                    diasEst++;
                }
                noches.setText(diasEst+" dias");
                costototal.setText(String.format("%.2f", precioh*diasEst));
            }
        }
    }
    
    private void precios() {
        String eval,data;
    
    if (tarifas.getSelectedItem() != null) {
        String claseTarifa = tarifas.getSelectedItem().toString().trim().substring(0,1);
        String nombreTipoHab = txttipo.getText();
        
        
        List<Map<String, Object>> resultados = sql.executeParametrizedQuery(
            "SELECT rango, precio " +
            "FROM tarifario " +
            "INNER JOIN tiphab ON tarifario.id_tiphab = tiphab.id  " +
            "WHERE tiphab.nombre = ? AND tarifario.temporada = ?",
            nombreTipoHab, claseTarifa);
        
        try {
            for (Map<String, Object> fila : resultados) {
                {
                    eval = fila.get("rango").toString();
                    data = fila.get("precio").toString();
                    
                    if("a".equals(eval))
                        precioa.setText(data);
                    else if("m".equals(eval))
                        preciom.setText(data);
                    
                }
            }
        } catch (NumberFormatException ex) {
            Logger.getLogger(panel3.class.getName()).log(Level.SEVERE, null, ex);
        }
    }
    calc();
    calculo();
}
    
    public void calculo(){
        float sumaadulto=val.stringtofloat(precioa.getText()), 
                sumamenor=val.stringtofloat(preciom.getText()),
                canta=Integer.parseInt(adulto.getValue().toString()),
                cantm=Integer.parseInt(menor.getValue().toString()),
                multia=sumaadulto*canta,
                multim=sumamenor*cantm,
                suma=multia+multim,
                subtotal=val.stringtofloat(noches.getText());
        
        costonoche.setText(String.format("%.2f", suma));
        subtotal=subtotal*suma;
        costototal.setText(String.format("%.2f", subtotal));
        
        
    }
    
    public Object[] costo() {
        if(indate.getDate()!=null&&outdate.getDate()!=null)
        {
            Object[] dato = new Object[4];
            dato[0] = txtnumero.getText();
            Date date = indate.getDate();
            java.sql.Date date1=new java.sql.Date(date.getYear(), date.getMonth(), date.getDate());
            if(antes)
                date1 = codex.restarFechasDias(date1, 1);
            dato[1]=date1;
            if(noches.getText().replaceAll("dias", " ").trim().length()>0)
                dato[2]=Integer.valueOf(noches.getText().replaceAll("dias", " ").trim());
            else
                dato[2]=0;
            
            precioh= Float.parseFloat(costonoche.getText().replace(",", "."));
            dato[3]=precioh;
            return dato;
        }
        return null;
    }
    
