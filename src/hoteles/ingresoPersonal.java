    private void confirmarKeyReleased(java.awt.event.KeyEvent evt) {
        int x1 = clave.getPassword().length;
        int x2 = confirmar.getPassword().length;
        
        if(x1 == x2) {
            char[] pass = clave.getPassword();
            char[] pass1 = confirmar.getPassword();
            boolean iguales = true;
            for(int i = 0; i < x1; i++) {
                if(pass[i] != pass1[i]) {
                    iguales = false;
                    break;
                }
            }
            repestado.setText(iguales ? "bueno" : "malo");
        } else if(x2 == 0) {
            repestado.setText("");
        } else {
            repestado.setText("malo");
        }
    }
    
