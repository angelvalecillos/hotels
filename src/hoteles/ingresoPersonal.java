    private void fotoMouseClicked(java.awt.event.MouseEvent evt) {
        FileNameExtensionFilter filtro = new FileNameExtensionFilter("jpg File","jpg");
        JFileChooser se = new JFileChooser();
        se.setFileSelectionMode(JFileChooser.FILES_ONLY);
        se.setFileFilter(filtro);
        int estado = se.showOpenDialog(null);
        
        if(estado == JFileChooser.APPROVE_OPTION) {
            try {
                Image icono = ImageIO.read(se.getSelectedFile()).getScaledInstance(foto.getWidth(), foto.getHeight(), Image.SCALE_DEFAULT);
                foto.setIcon(new ImageIcon(icono));
                foto.updateUI();
                newimagen = true;
                imageRoute = se.getSelectedFile().getAbsolutePath();
                imageName = se.getSelectedFile().getName();
            } catch (IOException ex) {
                Logger.getLogger(ingresoPersonal.class.getName()).log(Level.SEVERE, "Error al cargar imagen", ex);
                JOptionPane.showMessageDialog(this, "Error al cargar la imagen", "Error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }
    
