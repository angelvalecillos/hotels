    private boolean comparar() {
        int x1 = clave.getPassword().length;
        int x2 = confirmar.getPassword().length;
        if(x1 == x2) {
            char[] pass = clave.getPassword();
            char[] pass1 = confirmar.getPassword();
            for(int i = 0; i < x1; i++)
                if(pass[i] != pass1[i])
                    return false;
            return true;
        }
        return false;
    }
    
