    private void buscar() {
    int s;
    String ids = "";
    int n = txtnombre.getText().length();
    if(n != 0)
        s = sql.SelectCount("tiphab", "nombre='"+txtnombre.getText()+"'");
    else
        s = n;
    
    if(s != 0) {
        String cols = "capacidad, banos, cama, tv, aire, cocina, terraza, otros, imagen, id";
        String where = "nombre='"+txtnombre.getText()+"'";
        
        // Corregido: usar SqlQuery que devuelve List<Map<String, Object>>
        List<Map<String, Object>> resultados = sql.Select("tiphab", cols, where);
        
        if (!resultados.isEmpty()) {
            Map<String, Object> fila = resultados.get(0);
            
            if(fila.get("capacidad") != null)
                txtpersonas.setText(fila.get("capacidad").toString());
            if(fila.get("banos") != null)
                txtbanos.setText(fila.get("banos").toString());
            if(fila.get("cama") != null)
                txtcamas.setText(fila.get("cama").toString());
            if(fila.get("tv") != null)
                txttv.setText(fila.get("tv").toString());
            if(fila.get("aire") != null)
                txtaire.setText(fila.get("aire").toString());
            
            String c = fila.get("cocina") != null ? fila.get("cocina").toString() : "FALSE";
            if("TRUE".equals(c))
                cocina.setSelected(true);
            else
                cocina.setSelected(false);
            
            c = fila.get("terraza") != null ? fila.get("terraza").toString() : "FALSE";
            if("TRUE".equals(c))
                Terraza.setSelected(true); // Corregí: era cocina en lugar de terraza
            else
                Terraza.setSelected(false); // Corregí: era cocina en lugar de terraza
            
            if(fila.get("otros") != null)
                txtobservacion.setText(fila.get("otros").toString());
            txtobservacion.setPreferredSize(obsize);
            
            if(fila.get("imagen") != null)
                tiponame = fila.get("imagen").toString();
            if(fila.get("id") != null)
                ids = fila.get("id").toString();
        }
        
        cargaTarifas(ids);
        
        try {
            Image imagen1 = sql.getImagen(tiponame);
            if(imagen1 != null) {
                imagen.setIcon(new ImageIcon(imagen1));
                imagen.updateUI();
                newimagen = true;
            } else {
                imagen.setIcon(new javax.swing.ImageIcon(getClass().getResource("/imagenes/no disponible.jpg"))); // NOI18N
                imagen.updateUI();
                newimagen = false;
            }
        } catch (SQLException ex) {
            Logger.getLogger(ingresoTipohab.class.getName()).log(Level.SEVERE, null, ex);
        }
    } else {
        String leer = "";
        try {
            leer = arch.leer("ini\\transfer.txt", "");
            arch.nuevo("ini\\transfer.txt");
        } catch (IOException ex) {
            Logger.getLogger(ingresoTipohab.class.getName()).log(Level.SEVERE, null, ex);
        }
        leer = leer.trim();
        if(!"".equals(leer)) { // Corregí: usar equals para comparar strings
            txtnombre.setText(leer);
        } else {
            b.listin();
            b.setVisible(true);
        }
    }
}
    
