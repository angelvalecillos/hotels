    private boolean guardar() {
    String valor,
            tablas = "tiphab",
            campos = "nombre,capacidad,banos,cama,tv,aire,cocina,terraza,otros,imagen";
    valor = "'" + txtnombre.getText() + "','" +
            txtpersonas.getText() + "','" +
            txtbanos.getText() + "','" +
            txtcamas.getText() + "','" +
            txttv.getText() + "','" +
            txtaire.getText() + "','" +
            cocina.isSelected() + "','" +
            Terraza.isSelected() + "','" +
            txtobservacion.getText() + "','" +
            txtnombre.getText() + "@tiphab'";
    
    boolean Insert = false;
    int SelectCount = sql.SelectCount("tiphab", "nombre='" + txtnombre.getText() + "'");
    if(SelectCount == 0)
        Insert = sql.Insert(tablas, campos, valor);
    else
        Insert = sql.Update("tiphab", 
                  "nombre='" + txtnombre.getText() + "', "
                + "capacidad='" + txtpersonas.getText() + "', "
                + "banos='" + txtbanos.getText() + "', "
                + "cama='" + txtcamas.getText() + "', "
                + "tv='" + txttv.getText() + "', "
                + "aire='" + txtaire.getText() + "', "
                + "cocina='" + cocina.isSelected() + "', "
                + "terraza='" + Terraza.isSelected() + "', "
                + "otros='" + txtobservacion.getText() + "', "
                + "imagen='" + txtnombre.getText() + "@tiphab'", "nombre='" + txtnombre.getText() + "'");
    
    if (newimagen)
        sql.guardarFoto(imageName, imageRoute, txtnombre.getText() + "@tiphab");
    
    // Corregido: usar SqlQuery que devuelve List<Map<String, Object>>
    List<Map<String, Object>> resultados = sql.SqlQuery("select id from tiphab where nombre = '" + txtnombre.getText() + "'");
    if (!resultados.isEmpty()) {
        Map<String, Object> fila = resultados.get(0);
        if (fila.get("id") != null) {
            guardarTarifas(fila.get("id").toString());
        }
    }
    
    resetvalor();
    return Insert;
}
    
