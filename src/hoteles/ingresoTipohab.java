    private void cargaTarifas(String id){
    int CountTarifa = sql.SelectCount("tarifario", "id_tiphab="+id+"");
        txtadultoalta.setText("");
        txtadultobaja.setText("");
        txtmenoralta.setText("");
        txtmenorbaja.setText("");
    for (int i = 0; i < CountTarifa; i++) {
        // Corregido: usar SqlQuery que devuelve List<Map<String, Object>>
        List<Map<String, Object>> resultados = sql.SqlQuery("SELECT temporada, rango, precio from tarifario where id_tiphab='" + id + "'");
        if(resultados!=null){
            for (Map<String, Object> fila : resultados) {
                String temporada = fila.get("temporada") != null ? fila.get("temporada").toString().trim().toLowerCase() : "";
                String rango = fila.get("rango") != null ? fila.get("rango").toString().trim().toLowerCase() : "";
                String precio = fila.get("precio") != null ? fila.get("precio").toString().trim() : "";
                
                char t = temporada.isEmpty() ? '\0' : temporada.charAt(0); // 'a' o 'b'
                char r = rango.isEmpty() ? '\0' : rango.charAt(0);       // 'a' o 'm'

                
                if (t == 'a' && r == 'a') {
                    txtadultoalta.setText(precio);
                } else if (t == 'b' && r == 'a') {
                    txtadultobaja.setText(precio);
                } else if (t == 'a' && r == 'm') {
                    txtmenoralta.setText(precio);
                } else if (t == 'b' && r == 'm') {
                    txtmenorbaja.setText(precio);
                } else {
                // Si hay valores inesperados, puedes loguearlos o ignorarlos
                 System.out.println("Fila ignorada por temporada/rango inesperado: " + fila);
            }
        
            }
        }
       
        
    }
    }
    
