    private void mostrar(){
        String leer="";
        try {
            leer = txt.leer("ini\\ini.txt", "\n");
        } catch (IOException ex) {
        }
        int x=leer.split("\n").length;
        if (x==7)
        {
            String[] split = leer.split("\n");
            txt_JBDC.setText(split[0]);
            txt_IP.setText(split[1]);
            txt_PUERTO.setText(split[2]);
            txt_NOMBRE.setText(split[3]);
            txt_DRIVER.setText(split[4]);
            txt_USUARIO.setText(split[5]);
            txt_CLAVE.setText(split[6]);
        }
    }
    
    private boolean guardar(){
        try {
            txt.nuevo("ini\\ini.txt");
            txt.escribir("ini\\ini.txt", txt_JBDC.getText());
            txt.escribir("ini\\ini.txt", txt_IP.getText());
            txt.escribir("ini\\ini.txt", txt_PUERTO.getText());
            txt.escribir("ini\\ini.txt", txt_NOMBRE.getText());
            txt.escribir("ini\\ini.txt", txt_DRIVER.getText());
            txt.escribir("ini\\ini.txt", txt_USUARIO.getText());
            txt.escribir("ini\\ini.txt", txt_CLAVE.getText());
            return true;
        } catch (IOException ex) {
            Logger.getLogger(InstallDB.class.getName()).log(Level.SEVERE, null, ex);
            return false;
        }
        
    }
    
    private void bntGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bntGuardarActionPerformed
        boolean test=guardar();
        String mensaje;
        if(test)
            mensaje="base de datos actualizada, reinicie el programa";
        else
            mensaje="error al guardar datos";
        JOptionPane.showMessageDialog(null, mensaje);
        dispose();
    }//GEN-LAST:event_bntGuardarActionPerformed

